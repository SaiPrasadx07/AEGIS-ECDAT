"""
Aegis PQC — ECDAT service adapter.

A thin orchestration layer between the GUI and the ECDAT backend. It runs the
established pipeline in order and returns the results; it contains **no
discovery, risk, recommendation, or prioritisation logic of its own**. Every
number the GUI shows comes from a backend module through this adapter.

    discovery adapters
          ↓
    inventory  (context resolution)
          ↓
    cbom · quantum_risk · recommendations · migration_priority
          ↓
    PipelineResult  ← one object the GUI reads

WHY THIS EXISTS
---------------
The GUI must not call five backends and join them itself — that would put
business logic in the presentation layer. This adapter does the joining once,
deterministically, so the GUI is pure presentation and the backend stays the
single source of truth.

SAFETY
------
Runs only the backends, which are themselves execution-free. It adds no
subprocess, network, or filesystem behaviour beyond the discovery scanners'
own Phase 1–5 safety boundaries. The demo estate is generated by the existing
fixtures, never recreated here.
"""

