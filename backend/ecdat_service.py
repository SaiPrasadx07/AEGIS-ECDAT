def build_demo_estate(root: Path) -> Path:
    """Materialise the full demo estate using the existing fixtures.

    Reuses every Phase 1–5 fixture and appends the risk-policy block the
    quantum-risk engine reads. The estate is never recreated here — this only
    calls the fixtures and stitches the policy.

    Returns:
        The estate root.
    """
    demo_enterprise.generate(root, force=True)
    demo_manifests.write_application_manifests(root)
    demo_source.write_application_source(root)
    demo_binaries.write_application_binaries(root)

    policy_path = root / "aegis_policy.yaml"
    existing = policy_path.read_text(encoding="utf-8") if policy_path.exists() else ""
    if "quantum_risk:" not in existing:
        policy_path.write_text(
            existing + "\nquantum_risk:\n  crqc_horizon_years: 10\n"
            "  default_migration_years: 3\n",
            encoding="utf-8",
        )
    return root


