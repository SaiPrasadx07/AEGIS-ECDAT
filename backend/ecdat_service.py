def run_pipeline(
    target: Path,
    surfaces: tuple[str, ...] = ("certificates", "dependencies", "source", "binary"),
    limits: ScanLimits | None = None,
) -> PipelineResult:
    """Run the full ECDAT pipeline over a target directory.

    Args:
        target: Estate or repository root to scan.
        surfaces: Which discovery surfaces to run. Defaults to the four on-disk
            surfaces (container scanning takes an archive, handled separately).
        limits: Optional scan limits, passed through to the adapters.

    Returns:
        A :class:`PipelineResult` with every stage's output aligned by finding
        id. A missing target yields a result carrying an error, not an
        exception.
    """
    target = Path(target)
    result = PipelineResult(target=str(target))

    if not target.exists():
        result.errors.append(f"Target does not exist: {target}")
        return result

    policy_map = inventory.load_policy(target)
    raw_policy = inventory._parse_policy_file(target / "aegis_policy.yaml")
    resolver = ComponentResolver(extract_declared_paths(raw_policy))
    result.policy = qr.load_risk_policy(target)

    # --- discovery ---
    findings: list[CryptoFinding] = []
    if "certificates" in surfaces:
        scan = certificates.CERTIFICATE_ADAPTER.scan(target, "ecdat", limits)
        findings.extend(scan.findings)
        result.errors.extend(f"certificates: {e}" for e in scan.errors)
    if "dependencies" in surfaces:
        scan = dependencies.DEPENDENCY_ADAPTER.scan(target, "ecdat", limits, resolver=resolver)
        findings.extend(scan.findings)
        result.errors.extend(f"dependencies: {e}" for e in scan.errors)
    if "source" in surfaces:
        scan = source.SOURCE_ADAPTER.scan(target, "ecdat", limits, resolver=resolver)
        findings.extend(scan.findings)
        result.errors.extend(f"source: {e}" for e in scan.errors)
    if "binary" in surfaces and binary.LIEF_AVAILABLE:
        scan = binary.BINARY_ADAPTER.scan(target, "ecdat", limits, resolver=resolver)
        findings.extend(scan.findings)
        result.errors.extend(f"binary: {e}" for e in scan.errors)

    result.findings = findings
    if not findings:
        return result

    # --- context resolution ---
    result.contexts = {
        component: inventory.resolve_context(component, policy_map)
        for component in {f.component for f in findings if f.component}
    }

    # --- assessment chain (each stage consumes the previous) ---
    result.risks = qr.assess_inventory(findings, result.contexts, result.policy)
    result.recommendations = rec.recommend_batch(findings, result.risks)
    result.priorities = mp.prioritize_batch(result.recommendations, result.contexts)
    result.roadmap = mp.build_roadmap(result.priorities, result.recommendations)

    return result


