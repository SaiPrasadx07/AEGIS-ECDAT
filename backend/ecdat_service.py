@dataclass(slots=True)
class PipelineResult:
    """Everything the GUI needs from one ECDAT run.

    Findings, risk results, recommendations, and priorities are aligned by
    ``finding_id``. The roadmap and CBOM are derived views. The policy and
    contexts are carried so the GUI can show assumptions with provenance.
    """

    target: str
    findings: list[CryptoFinding] = field(default_factory=list)
    risks: list[QuantumRiskResult] = field(default_factory=list)
    recommendations: list[RecommendationResult] = field(default_factory=list)
    priorities: list[MigrationPriorityResult] = field(default_factory=list)
    roadmap: dict[str, list[dict[str, Any]]] = field(default_factory=dict)
    contexts: dict[str, ApplicationContext] = field(default_factory=dict)
    policy: qr.RiskPolicy | None = None
    errors: list[str] = field(default_factory=list)

    @property
    def is_empty(self) -> bool:
        return not self.findings


