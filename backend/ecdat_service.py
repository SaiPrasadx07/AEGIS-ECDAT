def overview_metrics(result: PipelineResult) -> dict[str, int]:
    """Headline counts for the Overview surface, all backend-derived."""
    by_source: dict[str, int] = {}
    for finding in result.findings:
        by_source[finding.source_type.value] = by_source.get(finding.source_type.value, 0) + 1

    risk_summary = qr.risk_summary(result.risks)
    priority_summary = mp.summarize(result.priorities)

    return {
        "total_findings": len(result.findings),
        "components": len({f.component for f in result.findings if f.component}),
        "certificates": by_source.get("certificate_file", 0),
        "dependencies": by_source.get("dependency", 0),
        "source_findings": by_source.get("source_code", 0),
        "binary_findings": by_source.get("binary", 0),
        "container_findings": by_source.get("container", 0),
        "quantum_vulnerable": risk_summary["by_quantum_category"].get("quantum_vulnerable", 0),
        "post_quantum": risk_summary["by_quantum_category"].get("post_quantum", 0),
        "capability_only": risk_summary["by_quantum_category"].get("capability_only", 0),
        "immediate": priority_summary["by_priority"].get("immediate", 0),
        "actionable": priority_summary["actionable"],
    }


def cbom_document(result: PipelineResult) -> str:
    """The CycloneDX CBOM for the current findings. Delegates to Phase 6."""
    return cbom.generate_cbom(result.findings)


def cbom_stats(result: PipelineResult) -> dict[str, int]:
    """Component/library counts for the CBOM surface, from the generated CBOM."""
    import json

    document = cbom.generate_cbom(result.findings)
    parsed = json.loads(document)
    components = parsed.get("components", [])

    crypto_assets = sum(1 for c in components if c.get("type") == "cryptographic-asset")
    libraries = sum(1 for c in components if c.get("type") == "library")
    capability_only = 0
    for component in components:
        for prop in component.get("properties", []):
            if prop.get("name") == "aegis:capability_only" and prop.get("value") == "true":
                capability_only += 1
                break

    return {
        "components": len(components),
        "crypto_assets": crypto_assets,
        "libraries": libraries,
        "capability_only": capability_only,
    }


def risk_by_finding(result: PipelineResult) -> dict[str, QuantumRiskResult]:
    """Index the risk results by finding id, for detail joins."""
    return {r.finding_id: r for r in result.risks}


def recommendation_by_finding(result: PipelineResult) -> dict[str, RecommendationResult]:
    """Index the recommendations by finding id, for detail joins."""
    return {r.finding_id: r for r in result.recommendations}


def priority_by_finding(result: PipelineResult) -> dict[str, MigrationPriorityResult]:
    """Index the priorities by finding id, for detail joins."""
    return {p.finding_id: p for p in result.priorities}


def migration_items(result: PipelineResult) -> list[MigrationPriorityResult]:
    """Actionable migration items only — NO_ACTION excluded, as it is not work."""
    return [
        p for p in result.priorities if p.priority is not MigrationPriority.NO_ACTION
    ]


def assumptions_view(result: PipelineResult) -> list[dict[str, Any]]:
    """The configured assumptions with provenance, for the Settings surface."""
    if result.policy is None:
        return []
    policy = result.policy
    rows = [
        ("CRQC horizon", policy.crqc_horizon_years, policy.source),
        ("Default migration time", policy.default_migration_years, policy.source),
        ("Default data lifetime", policy.default_data_lifetime_years, policy.source),
    ]
    return [
        {
            "name": name,
            "value": f"{value:g} years" if value is not None else "not configured",
            "provenance": provenance if value is not None else "missing",
        }
        for name, value, provenance in rows
    ]


def context_view(result: PipelineResult) -> list[dict[str, Any]]:
    """Declared organisation context per component, with provenance."""
    rows: list[dict[str, Any]] = []
    for component in sorted(result.contexts):
        context = result.contexts[component]
        rows.append(
            {
                "component": component,
                "data_lifetime_years": context.data_lifetime_years,
                "data_sensitivity": context.data_sensitivity.value,
                "business_criticality": context.business_criticality.value,
                "provenance": context.context_source.value,
                "is_declared": context.is_declared,
            }
        )
    return rows
